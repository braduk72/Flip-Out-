export function getDeckBackImage(deck) {
  return '/images/back.webp'
}

export function getDeckImages(deck, count) {
  const ownedIds = JSON.parse(localStorage.getItem('fo_owned_decks') || '[]')
  const fullyOwned = deck.free || ownedIds.includes(deck.id)
  const start = deck.cardStart ?? 1
  const availableCount = fullyOwned ? deck.cardCount : Math.min(FREE_CARD_COUNT, deck.cardCount)
  const indices = Array.from({ length: availableCount }, (_, i) => i + start)
  const shuffled = indices.sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count).map(i => ({
    image: `${deck.path}/${i}.webp`,
    name: deck.cardNames ? deck.cardNames[i - start] : null,
  }))
}
